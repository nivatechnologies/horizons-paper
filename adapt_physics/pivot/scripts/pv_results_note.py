"""Generate the pivot section of the vault note R_Adapt-The-Physics-Results-2026-09 from result files (no retyped
numbers). Writes pivot/results/results_note_pivot.md. Every table prints its source file.
"""
import csv
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from ap import config  # noqa: E402

R = config.PKG / "pivot" / "results"


def rd(name):
    return list(csv.DictReader(l for l in open(R / name) if not l.startswith("#")))


def f(x, n=3):
    try:
        return f"{float(x):.{n}f}"
    except (TypeError, ValueError):
        return str(x)


def src(name):
    return f"\n*Source: `adapt_physics/pivot/results/{name}`*\n"


def added(path):
    r = subprocess.run(["git", "log", "--diff-filter=A", "--format=%h", "--", path], cwd=config.PKG / "pivot",
                       capture_output=True, text=True).stdout.split()
    return r[-1] if r else "?"


def main():
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=config.PKG, capture_output=True, text=True).stdout.strip()
    bc = json.loads((R / "beta_calibration.json").read_text())
    L = ["", "## Pivot kill test: physics plus learned correction (WO 2026-09-26)", "",
         f"Generated by `adapt_physics/pivot/scripts/pv_results_note.py` at `{head}`.",
         f"- **Step 0:** the blinded Codex mismatch term was committed first (`{added('CODEX_MISMATCH.md')}`).",
         f"- **Freeze:** `{added('pv_freeze.yaml')}`, committed before any pivot test data.",
         "- **Gate:** `adapt_physics/pivot/PV_GATE.md`. **NUMBERS:** sections APV\\*.",
         f"- **World C:** World D plus topographic β, with β_T = {f(bc['beta'], 3)}. That changes enstrophy dissipation by "
         f"{f(100 * bc['rel_change'], 1)}% at Re 40. Codex proposed the term and its target; the executor tuned β_T to "
         "that target.",
         "- **H:** no-drag physics plus a 2.37 M-parameter learned correction trained on Re 40 data only. Re is identified "
         "on the hybrid.", ""]
    o = rd("pv_outcome.csv")[0]
    L += ["### Pre-committed outcome (w = 11, ε = 0.1, 300 states)", "", f"**{o['outcome']}**. Precedence: {o['precedence']}.",
          "", "| Criterion | World | Re | Value | Threshold | Holds |", "|---|---|---|---|---|---|"]
    for c in rd("pv_conditions.csv"):
        L.append(f"| {c['criterion']} | {c['world']} | {c['Re']} | {f(c['value'])} | {c['threshold']} | {c['holds']} |")
    L.append(src("pv_conditions.csv"))
    rows = rd("pv_rows.csv")
    L += ["### Horizons at w = 11, ε = 0.1 (Lyapunov times of the test system; retention = share of O)", "",
          "| World | Re | O | H | H+true Re | P1x | L_range | L0 | L0-big | P1 | H/O | H/L_range |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for wd in ("D", "C"):
        for Re in ("36", "40", "44", "50", "56"):
            g = {r["arm"]: r for r in rows if r["world"] == wd and r["Re"] == Re and r["w"] == "11" and r["eps"] == "0.1"}
            if not g:
                continue
            v = lambda a: f(g[a]["restricted_mean"], 2) if a in g else "—"  # noqa: E731
            L.append(f"| {wd} | {Re} | {v('O')} | {v('H')} | {v('H_true')} | {v('P1x')} | {v('L_range')} | {v('L0')} | "
                     f"{v('L0big')} | {v('P1')} | {f(g['H']['retention'], 2) if 'H' in g else '—'} | "
                     f"{f(g['H']['ratio_to_L_range'], 2) if 'H' in g else '—'} |")
    L.append("\n95% intervals, S(1), S(3), physical time, every w and ε: NUMBERS APVH." + src("pv_rows.csv"))
    L += ["### Key paired differences (w = 11, ε = 0.1)", "", "| World | Re | a | b | diff [95%] | reading |",
          "|---|---|---|---|---|---|"]
    for p in rd("pv_paired.csv"):
        if p["w"] == "11" and p["eps"] == "0.1" and (p["a"], p["b"]) in {("H", "L_range"), ("H", "O"), ("H_true", "H")}:
            L.append(f"| {p['world']} | {p['Re']} | {p['a']} | {p['b']} | {f(p['diff'])} [{f(p['ci95_lo'])}, {f(p['ci95_hi'])}] | {p['reading']} |")
    L.append(src("pv_paired.csv"))
    if (R / "pv_detector.csv").exists():
        L += ["### Window-drift detector (identified Re against w; reported only)", "",
              "| World | Re | Arm | w 3 | w 6 | w 11 | w 23 | slope per frame [95%] |", "|---|---|---|---|---|---|---|---|"]
        for d in rd("pv_detector.csv"):
            L.append(f"| {d['world']} | {d['Re']} | {d['arm']} | {f(d.get('re_hat_w3'), 2)} | {f(d.get('re_hat_w6'), 2)} | "
                     f"{f(d.get('re_hat_w11'), 2)} | {f(d.get('re_hat_w23'), 2)} | {f(d['slope_per_frame'], 3)} "
                     f"[{f(d['slope_ci95_lo'], 3)}, {f(d['slope_ci95_hi'], 3)}] |")
        L.append(src("pv_detector.csv"))
    rc = rd("pv_recovery.csv")
    L += ["### Time to 90% of the oracle (ε = 0.1; smallest tested w)", "", "| World | Re | H | L_range | P1x | L0 |",
          "|---|---|---|---|---|---|"]
    for wd in ("D", "C"):
        for Re in ("36", "40", "44", "50", "56"):
            g = {r["arm"]: r["w_to_90pct_oracle"] for r in rc if r["world"] == wd and r["Re"] == Re and r["eps"] == "0.1"}
            if g:
                L.append(f"| {wd} | {Re} | {g.get('H', '—')} | {g.get('L_range', '—')} | {g.get('P1x', '—')} | {g.get('L0', '—')} |")
    L.append(src("pv_recovery.csv"))
    L += ["### Cost", "", "| Model | Parameters | Training conditions | Training states | Steps | Train seconds |",
          "|---|---|---|---|---|---|"]
    for t in rd("pv_training.csv"):
        L.append(f"| {t['model']} | {t['params']} | {t['training_conditions']} | {t['training_states']} | {t['steps']} | {f(t['train_seconds'], 0)} |")
    L.append("")
    L += ["| World | Arm | Online s/state (Re 50, w 11) |", "|---|---|---|"]
    for c in rd("pv_cost.csv"):
        if c["Re"] == "50" and c["w"] == "11":
            L.append(f"| {c['world']} | {c['arm']} | {f(c['wall_seconds_per_state'], 3)} |")
    L.append(src("pv_cost.csv"))
    L += ["Figures: PV1 retention against drift, PV2 window-drift detector, PV3 horizon against training conditions and "
          "online cost (`adapt_physics/pivot/figures/`, `04-Results/adapt-physics-figures/`).", ""]
    (R / "results_note_pivot.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
