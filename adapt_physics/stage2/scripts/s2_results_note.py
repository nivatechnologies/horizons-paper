"""Generate the stage-2 section of R_Adapt-The-Physics-Results-2026-09 (part A first) from result files; no retyped
numbers. Writes stage2/results/results_note_stage2.md.
"""
import csv
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from ap import config  # noqa: E402

R = config.PKG / "stage2" / "results"


def rd(name):
    p = R / name
    return list(csv.DictReader(l for l in open(p) if not l.startswith("#"))) if p.exists() else []


def f(x, n=3):
    try:
        return f"{float(x):.{n}f}"
    except (TypeError, ValueError):
        return "—" if x in (None, "") else str(x)


def src(name):
    return f"\n*Source: `adapt_physics/stage2/results/{name}`*\n"


def added(path):
    r = subprocess.run(["git", "log", "--diff-filter=A", "--format=%h", "--", path], cwd=config.PKG / "stage2",
                       capture_output=True, text=True).stdout.split()
    return r[-1] if r else "?"


def main():
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=config.PKG, capture_output=True, text=True).stdout.strip()
    o = rd("s2_outcome.csv")[0]
    L = ["", "## Stage 2: confirmation and robustness (WO 2026-09-26)", "",
         f"Generated by `adapt_physics/stage2/scripts/s2_results_note.py` at `{head}`.",
         f"- **Freeze:** `{added('s2_freeze.yaml')}`, committed before any fresh panel.",
         "- **Gate:** `adapt_physics/stage2/S2_GATE.md`. **NUMBERS:** APS\\*.",
         "- **Panels:** 300 fresh trajectories per Re and world, from never-used streams.",
         "- **Seeds:** 3 each for H, L_range and L0.",
         "- **Estimator:** seed-pooled per state, bootstrapped over trajectories with seeds resampled within each "
         "trajectory.", "",
         "### Part A: confirmation (pivot criteria, unchanged; w = 11, ε = 0.1)", "",
         f"**{o['outcome']}**. Precedence: {o['precedence']}.", "",
         "| Criterion | World | Re | Fresh value [95%] | Threshold | Holds | Screening value |", "|---|---|---|---|---|---|---|"]
    for c in rd("s2_conditions.csv"):
        L.append(f"| {c['criterion']} | {c['world']} | {c['Re']} | {f(c['value'])} [{f(c['ci95_lo'])}, {f(c['ci95_hi'])}] | "
                 f"{c['threshold']} | {c['holds']} | {f(c['screening_value'])} |")
    L.append(src("s2_conditions.csv"))
    rows = rd("s2_rows.csv")
    L += ["### Part A horizons (w = 11, ε = 0.1, future frames; seed-pooled; per-seed means in brackets)", "",
          "| World | Re | O | H [per seed] | L_range [per seed] | L_range-wide | L0 | L0-big | P1x | P1 | H/O |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for wd in ("D", "C"):
        for Re in ("36", "40", "44", "50", "56"):
            g = {r["arm"]: r for r in rows if r["world"] == wd and r["Re"] == Re and r["w"] == "11" and r["eps"] == "0.1"
                 and r["score"] == "future"}
            if not g:
                continue
            v = lambda a: f(g[a]["restricted_mean"], 2) if a in g else "—"  # noqa: E731
            ps = lambda a: f" [{g[a]['per_seed']}]" if a in g and int(g[a]["seeds"]) > 1 else ""  # noqa: E731
            L.append(f"| {wd} | {Re} | {v('O')} | {v('H')}{ps('H')} | {v('L_range')}{ps('L_range')} | {v('L_range_wide')} | "
                     f"{v('L0')} | {v('L0big')} | {v('P1x')} | {v('P1')} | {f(g['H']['retention'], 2) if 'H' in g else '—'} |")
    L.append(src("s2_rows.csv"))
    B = rd("s2_partB.csv")
    L += ["### Part B: robustness (reported, not criteria; seed 0 unless stated)", "", "**1. Train wider (L_range-wide, Re 30-60).**", "",
          "| World | Re | L_range-wide | H (3 seeds) | H / L_range-wide | L_range-wide / O |", "|---|---|---|---|---|---|"]
    for r in B:
        if r["item"] == "1 train wider":
            wd, Re = r["panel"].split("_")[-1], r["panel"].split("Re")[1].split("_")[0]
            L.append(f"| {wd} | {Re} | {f(r['restricted_mean'], 2)} [{f(r['ci95_lo'], 2)}, {f(r['ci95_hi'], 2)}] | "
                     f"{f(r.get('H_seed_pooled'), 2)} | {f(r.get('H_over_L_range_wide'), 2)} | {f(r.get('ratio_to_O'), 2)} |")
    tr = rd("s2_training.csv")
    L.append("\nTraining conditions: " + "; ".join(f"{t['model']}: Re {t['training_re_range']}, {t['training_conditions']} "
                                                  f"condition(s), {t['training_states']} states" for t in tr
                                                  if t["model"] in ("H_D", "H_C", "L_range", "L_range_C", "L_range_wide", "L_range_wide_C")) + ".")
    L += ["", "**2. Windows straddling the change (11 frames, starting 3, 6, 9 frames before t_c).**", "",
          "| Panel | Arm | Starts before t_c | Horizon [95%] | / O (standard window) |", "|---|---|---|---|---|"]
    for r in B:
        if r["item"] == "2 straddle":
            L.append(f"| {r['panel']} | {r['arm']} | {r['window_starts_before_tc']} | {f(r['restricted_mean'], 2)} "
                     f"[{f(r['ci95_lo'], 2)}, {f(r['ci95_hi'], 2)}] | {f(r.get('ratio_to_O_std'), 2)} |")
    L += ["", "**3. Two-parameter drift (World D: Re and forcing amplitude).**", "",
          "| Case | Arm | Horizon [95%] | / O | / L_range | median Re_hat | median A_hat |", "|---|---|---|---|---|---|---|"]
    for r in B:
        if r["item"] == "3 two parameters":
            L.append(f"| {r['panel'].replace('s2_test2p_', '')} | {r['arm']} | {f(r['restricted_mean'], 2)} [{f(r['ci95_lo'], 2)}, "
                     f"{f(r['ci95_hi'], 2)}] | {f(r.get('ratio_to_O'), 2)} | {f(r.get('ratio_to_L_range'), 2)} | "
                     f"{f(r.get('re_hat_median'), 2)} | {f(r.get('amp_hat_median'), 3)} |")
    L += ["", "**4. 5% sensor noise (w = 11).**", "", "| Panel | Arm | Horizon [95%] | / O (5%) |", "|---|---|---|---|"]
    for r in B:
        if r["item"] == "4 noise 5%":
            L.append(f"| {r['panel']} | {r['arm']} | {f(r['restricted_mean'], 2)} [{f(r['ci95_lo'], 2)}, {f(r['ci95_hi'], 2)}] | "
                     f"{f(r.get('ratio_to_O_noise5'), 2)} |")
    L.append(src("s2_partB.csv"))
    L += ["**5. Recovery (time to 90% of O, smallest of w = 3, 6, 11; ε = 0.1).**", "", "| World | Re | H | L_range | L_range-wide | P1x |",
          "|---|---|---|---|---|---|"]
    rc = rd("s2_recovery.csv")
    for wd in ("D", "C"):
        for Re in ("36", "40", "44", "50", "56"):
            g = {r["arm"]: r["w_to_90pct_oracle"] for r in rc if r["world"] == wd and r["Re"] == Re and r["eps"] == "0.1"}
            if g:
                L.append(f"| {wd} | {Re} | {g.get('H', '—')} | {g.get('L_range', '—')} | {g.get('L_range_wide', '—')} | {g.get('P1x', '—')} |")
    L += ["", "**6. Scoring convention (part-A cell, w = 11).** H / O and H / L_range under the other conventions:", "",
          "| World | Re | from t = 0, ε 0.1: H/O | H/L_range | future, ε 0.3: H/O | H/L_range |", "|---|---|---|---|---|---|"]
    for wd in ("D", "C"):
        for Re in ("36", "40", "44", "50", "56"):
            a = {r["arm"]: r for r in rows if r["world"] == wd and r["Re"] == Re and r["w"] == "11" and r["eps"] == "0.1" and r["score"] == "from_t0"}
            b = {r["arm"]: r for r in rows if r["world"] == wd and r["Re"] == Re and r["w"] == "11" and r["eps"] == "0.3" and r["score"] == "future"}
            if "H" in a and "H" in b:
                L.append(f"| {wd} | {Re} | {f(a['H']['retention'], 2)} | {f(a['H']['ratio_to_L_range'], 2)} | {f(b['H']['retention'], 2)} | "
                         f"{f(b['H']['ratio_to_L_range'], 2)} |")
    L += ["", "**7. Detector (identified Re against w = 3, 6, 11).**", "",
          "| World | Re | Arm | Re_hat w 3 / 6 / 11 | slope per frame [95%] | Spearman(slope, O − H) [95%] |", "|---|---|---|---|---|---|"]
    for d in rd("s2_detector.csv"):
        if d["arm"] in ("H", "P1"):
            L.append(f"| {d['world']} | {d['Re']} | {d['arm']} | {f(d['re_hat_w3'], 2)} / {f(d['re_hat_w6'], 2)} / {f(d['re_hat_w11'], 2)} | "
                     f"{f(d['slope_per_frame'], 4)} [{f(d['slope_ci95_lo'], 4)}, {f(d['slope_ci95_hi'], 4)}] | "
                     f"{f(d.get('spearman_slope_vs_shortfall'), 2)} [{f(d.get('spearman_ci95_lo'), 2)}, {f(d.get('spearman_ci95_hi'), 2)}] |")
    L.append(src("s2_detector.csv"))
    L += ["Figures: S2F1 retention, S2F2 recovery, S2F3 training conditions, S2F4 detector (`adapt_physics/stage2/figures/`, "
          "`04-Results/adapt-physics-figures/`).", ""]
    (R / "results_note_stage2.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:40]))


if __name__ == "__main__":
    main()
