"""Generate the objections-WO section of R_Adapt-The-Physics-Results-2026-09 from result files (no retyped numbers).
Writes stage2/objections/results/results_note_objections.md.
"""
import csv
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve()
PKG = HERE.parents[3]
sys.path.insert(0, str(PKG))
from ap import config  # noqa: E402

R = PKG / "stage2" / "objections" / "results"


def rd(name):
    p = R / name
    return list(csv.DictReader(l for l in open(p) if not l.startswith("#"))) if p.exists() else []


def f(x, n=3):
    try:
        return f"{float(x):.{n}f}"
    except (TypeError, ValueError):
        return "—" if x in (None, "") else str(x)


def src(name):
    return f"\n*Source: `adapt_physics/stage2/objections/results/{name}`*\n"


def main():
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=PKG, capture_output=True, text=True).stdout.strip()
    frz = subprocess.run(["git", "log", "--diff-filter=A", "--format=%h", "--", "obj_freeze.yaml"], cwd=R.parent,
                         capture_output=True, text=True).stdout.split()
    L = ["", "## Objections and edge timing (WO 2026-09-27)", "",
         f"Generated by `adapt_physics/stage2/objections/scripts/obj_results_note.py` at `{head}`.",
         f"- **Freeze:** `{frz[-1] if frz else '?'}`, committed before any World V data and any Part 2 evaluation.",
         "- **Gate:** `adapt_physics/stage2/objections/OBJ_GATE.md`. **NUMBERS:** APDD\\*, APFR\\*, APEDGE\\*.",
         "- **Estimator:** seed-pooled, with trajectories resampled and then seeds within each trajectory (as in stage-2 "
         "part A).", ""]
    cv = json.loads((R / "chaos_V.json").read_text())["Re50"] if (R / "chaos_V.json").exists() else None
    L += ["### Part 1: drag that drifts with viscosity (World V, Re 50; readings reported, not criteria)", ""]
    if cv:
        L.append(f"World V at Re 50: α = {f(cv['alpha'], 5)}, λ = {f(cv['lam'], 4)} [{f(cv['lam_ci95'][0], 4)}, "
                 f"{f(cv['lam_ci95'][1], 4)}], σ_A = {f(cv['sigma_A'], 1)}, chaotic: {cv['chaotic']}.")
    L += ["", "| ε | H/O [95%] | H/L_range_V [95%] | Outcome reading | H+true Re − H [95%] | World D part A: H/O, H/L_range |",
          "|---|---|---|---|---|---|"]
    for r in rd("obj_part1_readings.csv"):
        L.append(f"| {r['eps']} | {f(r['H_over_O'])} [{f(r['H_over_O_ci95_lo'])}, {f(r['H_over_O_ci95_hi'])}] | "
                 f"{f(r['H_over_L_range_V'])} [{f(r['H_over_L_range_V_ci95_lo'])}, {f(r['H_over_L_range_V_ci95_hi'])}] | "
                 f"**{r['outcome_reading']}** | {f(r.get('H_true_minus_H'))} [{f(r.get('H_true_minus_H_ci95_lo'))}, "
                 f"{f(r.get('H_true_minus_H_ci95_hi'))}] | {f(r['partA_D_Re50_H_over_O'])}, {f(r['partA_D_Re50_H_over_L_range'])} |")
    L += ["", "| Arm | Seeds | Horizon w 11, ε 0.1 [95%] | S(1) | S(3) | World D part A (Re 50) |", "|---|---|---|---|---|---|"]
    for r in rd("obj_part1.csv"):
        if r["w"] == "11" and r["eps"] == "0.1":
            L.append(f"| {r['arm']} | {r['seeds']} | {f(r['restricted_mean'], 2)} [{f(r['ci95_lo'], 2)}, {f(r['ci95_hi'], 2)}] | "
                     f"{f(r['S1'], 2)} | {f(r['S3'], 2)} | {f(r['partA_worldD_Re50'], 2)} |")
    L += ["", "Detectors (identified Re against w):", "", "| World | Re | Arm | Mean Re_hat | Bias | Slope per frame [95%] | Reading |",
          "|---|---|---|---|---|---|---|"]
    for d in rd("obj_detector.csv"):
        L.append(f"| {d['world']} | {d['Re']} | {d['arm']} | {f(d['mean_re_hat'], 2)} | {f(d['bias_from_true'], 2)} | "
                 f"{f(d['slope_per_frame'], 4)} [{f(d['slope_ci95_lo'], 4)}, {f(d['slope_ci95_hi'], 4)}] | {d.get('detector_reading', '')} |")
    L.append(src("obj_part1_readings.csv"))
    L += ["### Part 2: the network given the parameter (FNO-Re)", ""]
    for r in rd("obj_part2_reading.csv"):
        if r.get("claim"):
            L.append(f"**Frozen reading: {r['claim']}**.")
    L += ["", "| Re | H − (FNO-Re + true Re) [95%] | Seeds | Holds |", "|---|---|---|---|"]
    for r in rd("obj_part2_reading.csv"):
        if not r.get("claim"):
            L.append(f"| {r['Re']} | {f(r['H_minus_FNO_Re_true'])} [{f(r['ci95_lo'])}, {f(r['ci95_hi'])}] | {r['seeds']} | {r['holds_at_this_Re']} |")
    L += ["", "| World | Re | Arm | Seeds | Horizon [95%] | Retention | H (retention) | H − arm [95%] |", "|---|---|---|---|---|---|---|---|"]
    for r in rd("obj_part2.csv"):
        if r["eps"] == "0.1":
            L.append(f"| {r['world']} | {r['Re']} | {r['arm']} | {r['seeds']} | {f(r['restricted_mean'], 2)} [{f(r['ci95_lo'], 2)}, "
                     f"{f(r['ci95_hi'], 2)}] | {f(r['retention'], 2)} | {f(r['H'], 2)} ({f(r['H_retention'], 2)}) | "
                     f"{f(r['H_minus_arm'], 2)} [{f(r['diff_ci95_lo'], 2)}, {f(r['diff_ci95_hi'], 2)}] |")
    L += ["", "Fine-tuned FNO (L_ft, stage-1 procedure) on fresh World D panels, w = 11 (reported, not a reading):", "",
          "| Re | L_ft [95%] | Retention | H | H − L_ft [95%] | Online s/state |", "|---|---|---|---|---|---|"]
    for r in rd("obj_lft.csv"):
        L.append(f"| {r['Re']} | {f(r['restricted_mean'], 2)} [{f(r['ci95_lo'], 2)}, {f(r['ci95_hi'], 2)}] | {f(r['retention'], 2)} | "
                 f"{f(r['H'], 2)} | {f(r['H_minus_L_ft'], 2)} [{f(r['diff_ci95_lo'], 2)}, {f(r['diff_ci95_hi'], 2)}] | "
                 f"{f(r['online_seconds_per_state'], 2)} |")
    L.append(src("obj_part2.csv"))
    L += ["### Part 3: edge timing on an Orin NX (reported only; batch 1, FP32 networks, no TensorRT)", ""]
    e = rd("obj_edge.csv")
    if e:
        L.append(f"Orin host: `{e[0]['orin_host']}`. Datacenter (batch 1, same harness): `{e[0]['dc_host']}`.")
        L += ["", "| Arm | Result | Orin wall median / p90 (s) | Datacenter wall median (s) | Identify or adapt (s) | Orin fps | "
                  "Datacenter fps | Torch peak MB | RAM peak MB | VDD_IN mW | J/state | Max horizon diff |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in e:
            L.append(f"| {r['arm']} | {r['orin_result']} | {f(r['orin_wall_median'], 2)} / {f(r['orin_wall_p90'], 2)} | "
                     f"{f(r['dc_batch1_wall_median'], 2)} | {f(r['orin_identify_or_adapt_median'], 2)} | {f(r['orin_forecast_fps'], 1)} | "
                     f"{f(r['dc_batch1_forecast_fps'], 1)} | {f(r['orin_peak_torch_mem_MB'], 0)} | {f(r['orin_tegrastats_ram_peak_MB'], 0)} | "
                     f"{f(r['orin_vdd_in_mean_mW'], 0)} | {f(r['orin_energy_per_state_J'], 1)} | {f(r.get('horizon_max_abs_diff'), 3)} |")
        L.append(src("obj_edge.csv"))
    else:
        L.append("(pending)")
    (R / "results_note_objections.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
