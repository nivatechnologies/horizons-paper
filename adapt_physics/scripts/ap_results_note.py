"""Generate the vault results note R_Adapt-The-Physics-Results-2026-09 from result files (no retyped numbers).
Writes results/results_note.md (body without frontmatter; the publisher adds it). Every table prints its source file.
"""
import csv
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from ap import config  # noqa: E402

R = config.RESULTS


def rd(name):
    return list(csv.DictReader(l for l in open(R / name) if not l.startswith("#")))


def f(x, n=3):
    try:
        return f"{float(x):.{n}f}"
    except (TypeError, ValueError):
        return str(x)


def src(name):
    return f"\n*Source: `adapt_physics/results/{name}`*\n"


def commit_of(path):
    r = subprocess.run(["git", "log", "--diff-filter=A", "--format=%h", "--", path], cwd=config.PKG,
                       capture_output=True, text=True).stdout.split()
    return r[-1] if r else "?"


def main():
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=config.PKG, capture_output=True, text=True).stdout.strip()
    L = ["# Adapt the Physics: stage-1 kill test results", "",
         f"Generated by `adapt_physics/scripts/ap_results_note.py` at commit `{head}` on branch `paper/adapt-physics-2026-09`. "
         f"Freeze commit `{commit_of('ap_freeze.yaml')}` (AP_FREEZE.md, ap_freeze.yaml), made before any test-panel data "
         "and before learned-arm training beyond a 300-step timing pilot. Gate report: `adapt_physics/AP_GATE.md`. "
         "NUMBERS: `adapt_physics/NUMBERS.md` (sections AP*). Labels: reference / learned / estimate. Stage 1 is a "
         "screening panel: 300 independent trajectories per test Re (L_ft: first 100); stage 2 must confirm on fresh "
         "trajectories.", ""]
    # verdict
    v = rd("ap_kill_verdict.csv")[0]
    L += ["## Kill rule (frozen): outcome", "",
          f"**{v['outcome']}.** Cell: {v['cell']}. I* = {f(v['I_star'])} ({v['I_arm']}), A* = {f(v['A_star'])} "
          f"({v['A_arm']}); I*/A* = {f(v['ratio_44'], 2)} at Re 44, {f(v['ratio_50'], 2)} at Re 50, "
          f"{f(v['ratio_40'], 2)} at Re 40 (no drift). Pass needs ≥ 2 at Re 44 and Re 50; kill needs A* ≥ 0.75 I* "
          f"(ratio ≤ 1.33) at Re 44.", "",
          f"**No-drift flag: {'RAISED' if v['flag_no_drift_ratio_ge_drift'] == 'True' else 'not raised'}** "
          f"(the I*/A* ratio at Re 40 is {'at least' if v['flag_no_drift_ratio_ge_drift'] == 'True' else 'below'} "
          "the ratio at Re 44" + ("; the advantage is then not attributable to adaptation)." if
                                   v['flag_no_drift_ratio_ge_drift'] == 'True' else ")."), src("ap_kill_verdict.csv")]
    # kill table at w 11 eps 0.1
    kt = rd("ap_kill.csv")
    L += ["## I* and A* at w = 11 (first 100 states)", "",
          "| Re | ε | O | P1 | L_param+P1 | L_range | L_ft | L0-big | I* | A* | I*/A* | I*/A* (300, no L_ft) |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(kt, key=lambda r: (float(r["eps"]), int(r["Re"]))):
        if r["w"] == "11":
            L.append(f"| {r['Re']} | {r['eps']} | {f(r['O'])} | {f(r['P1'])} | {f(r['L_param_P1'])} | {f(r['L_range'])} | "
                     f"{f(r['L_ft'])} | {f(r['L0big'])} | {f(r['I_star'])} ({r['I_arm']}) | {f(r['A_star'])} ({r['A_arm']}) | "
                     f"{f(r['ratio'], 2)} | {f(r['ratio_300_without_Lft'], 2)} |")
    L.append("\nRestricted means in Lyapunov times of the test system (W = 10). Label: estimate (ratios); arms reference / learned.")
    L.append(src("ap_kill.csv"))
    # per-arm horizons at Re 44 w 11
    rows = rd("ap_rows.csv")
    L += ["## Every arm at w = 11 (all states the arm ran on)", "",
          "| Re | Arm | Role | n | ε 0.1: mean [95%] | time | S(1) | S(3) | ε 0.3: mean [95%] |", "|---|---|---|---|---|---|---|---|---|"]
    for Re in sorted({r["Re"] for r in rows}, key=int):
        for arm in dict.fromkeys(r["arm"] for r in rows):
            a = [r for r in rows if r["Re"] == Re and r["arm"] == arm and r["w"] == "11" and r["panel"] == "all"]
            e1 = [r for r in a if r["eps"] == "0.1"]
            e3 = [r for r in a if r["eps"] == "0.3"]
            if not e1:
                continue
            x, y = e1[0], e3[0] if e3 else {}
            L.append(f"| {Re} | {arm} | {x['role']} | {x['n']} | {f(x['restricted_mean'])} [{f(x['ci95_lo'])}, {f(x['ci95_hi'])}] | "
                     f"{f(x['phys_time'], 2)} | {f(x['S1'], 2)} | {f(x['S3'], 2)} | "
                     f"{f(y.get('restricted_mean'))} [{f(y.get('ci95_lo'))}, {f(y.get('ci95_hi'))}] |")
    L.append("\ntime = physical time units. Full grid (every w) in NUMBERS APH." + src("ap_rows.csv"))
    # paired key readings
    pr = rd("ap_paired.csv")
    L += ["## Key paired differences (a − b) at w = 11, ε = 0.1", "", "| Re | a | b | n | diff [95%] | reading |",
          "|---|---|---|---|---|---|"]
    for r in pr:
        if r["w"] == "11" and r["eps"] == "0.1" and (r["a"], r["b"]) in {("P1", "L_range"), ("L_param_P1", "L_range"),
                                                                        ("P1", "L_ft"), ("L_param_P1", "L_ft"),
                                                                        ("P1", "L0big"), ("O", "P1"), ("P1x", "P1"),
                                                                        ("L0big", "L0"), ("L_range", "L0")}:
            L.append(f"| {r['Re']} | {r['a']} | {r['b']} | {r['n']} | {f(r['diff'])} [{f(r['ci95_lo'])}, {f(r['ci95_hi'])}] | {r['reading']} |")
    L.append("\nReading 'b well below a' = a − b ≥ 0.25 with the 95% interval above 0." + src("ap_paired.csv"))
    # recovery
    rc = rd("ap_recovery.csv")
    L += ["## Time to 90% of the oracle (smallest tested w; ε = 0.1)", "",
          "| Arm | " + " | ".join(f"Re {Re}" for Re in sorted({r['Re'] for r in rc}, key=int)) + " |",
          "|---|" + "---|" * len({r['Re'] for r in rc})]
    for arm in dict.fromkeys(r["arm"] for r in rc):
        cells = []
        for Re in sorted({r["Re"] for r in rc}, key=int):
            x = [r for r in rc if r["arm"] == arm and r["Re"] == Re and r["eps"] == "0.1"]
            cells.append(x[0]["w_to_90pct_oracle"] if x else "")
        L.append(f"| {arm} | " + " | ".join(cells) + " |")
    L.append(src("ap_recovery.csv"))
    # identification
    if (R / "ap_identify.csv").exists():
        L += ["## Identified Re", "", "| Re | Arm | w | mean | SD | median |error| |", "|---|---|---|---|---|---|"]
        for r in rd("ap_identify.csv"):
            L.append(f"| {r['Re']} | {r['arm']} | {r['w']} | {f(r['re_hat_mean'], 2)} | {f(r['re_hat_sd'], 2)} | {f(r['median_abs_error'], 2)} |")
        L.append("\nP1 fits the no-drag family, so its Re absorbs the unmodeled drag (a bias, not an error of the search)."
                 + src("ap_identify.csv"))
    # cost
    L += ["## Online cost at Re 44, w = 11", "", "| Arm | wall s / state | solver steps (identify) | gradient steps |",
          "|---|---|---|---|"]
    for c in rd("ap_cost.csv"):
        if c["Re"] == "44" and c["w"] == "11":
            L.append(f"| {c['arm']} | {f(c['wall_seconds_per_state'], 3)} | {c['solver_steps_identify']} | {c['gradient_steps']} |")
    L.append(src("ap_cost.csv"))
    if (R / "ap_training.csv").exists():
        L += ["## Training cost", "", "| Model | Parameters | Steps | Seconds | Best step |", "|---|---|---|---|---|"]
        for t in rd("ap_training.csv"):
            L.append(f"| {t['model']} | {t['params']} | {t['steps']} | {f(t['train_seconds'], 0)} | {t['best_step']} |")
        L.append(src("ap_training.csv"))
    cg = json.loads((R / "chaos_gate.json").read_text())
    dc = json.loads((R / "drag_calibration.json").read_text())
    L += ["## System (drag calibration and chaos gate)", "",
          f"Drag α = {f(dc['alpha'], 5)} (share {f(dc['share'], 4)} of enstrophy dissipation at Re 40; target 0.15).", "",
          "| Re | λ [95%] | σ_A | chaotic |", "|---|---|---|---|"]
    for k, x in sorted(((k, x) for k, x in cg.items() if isinstance(x, dict)), key=lambda kv: kv[1]["Re"]):
        L.append(f"| {x['Re']:g} | {f(x['lam'], 4)} [{f(x['lam_ci95'][0], 4)}, {f(x['lam_ci95'][1], 4)}] | {f(x['sigma_A'], 1)} | {x['chaotic']} |")
    L.append(src("chaos_gate.json"))
    L += ["## Figures", "", "AP1 horizon against drift size, AP2 recovery curve, AP3 horizon against online cost: "
          "`adapt_physics/figures/` and `04-Results/adapt-physics-figures/` (PNG + CSV with SHA).", ""]
    (R / "results_note.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
